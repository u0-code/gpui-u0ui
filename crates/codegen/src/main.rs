//! `u0ui-codegen`: regenerates the committed sources derived from the Carbon UI
//! design reference, which lives outside the repository.
//!
//! ```text
//! U0UI_DESIGN_DIR=/path/to/design cargo run -p u0ui-codegen            # write
//! U0UI_DESIGN_DIR=/path/to/design cargo run -p u0ui-codegen -- --check # verify
//! ```
//!
//! | Input (under `$U0UI_DESIGN_DIR`) | Output |
//! | --- | --- |
//! | `tokens.json` | `crates/u0ui/src/generated/tokens.rs` |
//! | `src/icons/material.js` | `crates/u0ui/src/generated/carbon_icons.rs` |
//! | `components/<Name>/README.md` | `crates/gallery/src/generated/descriptions.rs` |
//!
//! `--check` writes nothing and exits non-zero when a committed file differs
//! from what would be generated.
use std::{
    path::{Path, PathBuf},
    process::ExitCode,
};

mod descriptions;
mod tokens;

/// First line of every generated file.
pub(crate) const HEADER: &str = "// @generated by u0ui-codegen; do not edit\n";

/// The environment variable naming the design reference directory.
const DESIGN_DIR_VAR: &str = "U0UI_DESIGN_DIR";

/// The workspace root (two levels above this crate).
fn workspace_root() -> PathBuf {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    root.canonicalize().unwrap_or(root)
}

fn read(path: &Path) -> Result<String, String> {
    std::fs::read_to_string(path).map_err(|e| format!("read {}: {e}", path.display()))
}

/// Every generated file as `(path relative to the workspace root, contents)`.
fn generate(design: &Path) -> Result<Vec<(&'static str, String)>, String> {
    if !design.is_dir() {
        return Err(format!(
            "{DESIGN_DIR_VAR}={} is not a directory",
            design.display()
        ));
    }
    Ok(vec![
        (
            "crates/u0ui/src/generated/tokens.rs",
            tokens::tokens(&read(&design.join("tokens.json"))?),
        ),
        (
            "crates/u0ui/src/generated/carbon_icons.rs",
            tokens::carbon_icons(&read(&design.join("src/icons/material.js"))?),
        ),
        (
            "crates/gallery/src/generated/descriptions.rs",
            descriptions::descriptions(&design.join("components"))?,
        ),
    ])
}

/// Paths of committed files that differ from `files`.
fn stale(root: &Path, files: &[(&'static str, String)]) -> Vec<&'static str> {
    files
        .iter()
        .filter(|(path, contents)| {
            std::fs::read_to_string(root.join(path)).ok().as_ref() != Some(contents)
        })
        .map(|(path, _)| *path)
        .collect()
}

fn run() -> Result<(), String> {
    let mut check = false;
    for arg in std::env::args().skip(1) {
        match arg.as_str() {
            "--check" => check = true,
            "-h" | "--help" => {
                println!("usage: {DESIGN_DIR_VAR}=<design dir> u0ui-codegen [--check]");
                return Ok(());
            }
            other => return Err(format!("unknown argument {other:?} (expected --check)")),
        }
    }
    let design = std::env::var_os(DESIGN_DIR_VAR).ok_or_else(|| {
        format!(
            "{DESIGN_DIR_VAR} is not set; point it at the Carbon UI design reference \
             (the directory holding tokens.json, components/ and src/)"
        )
    })?;
    let files = generate(Path::new(&design))?;
    let root = workspace_root();
    let stale = stale(&root, &files);
    if check {
        if stale.is_empty() {
            println!("generated sources are up to date");
            return Ok(());
        }
        return Err(format!(
            "generated sources are stale (run `cargo run -p u0ui-codegen`): {}",
            stale.join(", ")
        ));
    }
    for (path, contents) in &files {
        if !stale.contains(path) {
            continue;
        }
        let path = root.join(path);
        std::fs::create_dir_all(path.parent().unwrap())
            .and_then(|()| std::fs::write(&path, contents))
            .map_err(|e| format!("write {}: {e}", path.display()))?;
        println!(
            "wrote {}",
            path.strip_prefix(&root).unwrap_or(&path).display()
        );
    }
    Ok(())
}

fn main() -> ExitCode {
    match run() {
        Ok(()) => ExitCode::SUCCESS,
        Err(message) => {
            eprintln!("u0ui-codegen: {message}");
            ExitCode::FAILURE
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The design directory, or `None` (test skipped) when it is not configured.
    fn design_dir() -> Option<PathBuf> {
        let dir = std::env::var_os(DESIGN_DIR_VAR).map(PathBuf::from);
        if dir.is_none() {
            eprintln!("{DESIGN_DIR_VAR} not set; skipping");
        }
        dir
    }

    #[test]
    fn committed_sources_are_fresh() {
        let Some(design) = design_dir() else { return };
        let files = generate(&design).unwrap();
        assert_eq!(stale(&workspace_root(), &files), Vec::<&str>::new());
    }

    /// Every hex color in `tokens.json` survives parsing (the generated tables
    /// hold exactly these values), and token names stay unique.
    #[test]
    fn json_hex_values_round_trip() {
        let Some(design) = design_dir() else { return };
        let json: serde_json::Value =
            serde_json::from_str(&read(&design.join("tokens.json")).unwrap()).unwrap();
        let hex = |[r, g, b, _]: [f32; 4]| {
            let byte = |v: f32| (v * 255.).round() as u8;
            format!("#{:02x}{:02x}{:02x}", byte(r), byte(g), byte(b))
        };
        let tokens = json["color"]["tokens"].as_array().unwrap();
        let mut names = std::collections::HashSet::new();
        for token in tokens {
            let name = token["name"].as_str().unwrap();
            assert!(names.insert(name), "duplicate token {name}");
            if let Some(values) = token["value"].as_object() {
                for theme in ["white", "g10", "g90", "g100"] {
                    let want = values[theme].as_str().unwrap();
                    if want.len() == 7 && want.starts_with('#') {
                        assert_eq!(hex(tokens::parse_color(want)), want, "{name} {theme}");
                    }
                }
            }
        }
    }

    #[test]
    fn parses_color_forms() {
        assert_eq!(tokens::parse_color("transparent"), [0., 0., 0., 0.]);
        assert_eq!(tokens::parse_color("#fff"), [1., 1., 1., 1.]);
        assert_eq!(tokens::parse_color("#0000ff80")[3], 128. / 255.);
        assert_eq!(
            tokens::parse_color("rgba(141, 141, 141, 0.12)"),
            [141. / 255., 141. / 255., 141. / 255., 0.12]
        );
    }
}
