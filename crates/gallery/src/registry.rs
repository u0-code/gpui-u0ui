/// Look a page up by id.
pub fn find(id: &str) -> Option<usize> {
    PAGES.iter().position(|p| p.id == id)
}

/// The navigation groups: [`GROUP_ORDER`], then any other group in first-use
/// order.
pub fn groups() -> Vec<&'static str> {
    let mut groups: Vec<&'static str> = GROUP_ORDER
        .iter()
        .copied()
        .filter(|g| PAGES.iter().any(|p| p.group == *g))
        .collect();
    for page in PAGES {
        if !groups.contains(&page.group) {
            groups.push(page.group);
        }
    }
    groups
}

/// The pages of `group` with their indices in [`PAGES`], in navigation order.
pub fn pages_in(group: &str) -> impl Iterator<Item = (usize, &'static PageDef)> + '_ {
    PAGES
        .iter()
        .enumerate()
        .filter(move |(_, p)| p.group == group)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn ids_are_unique_and_descriptions_present() {
        for (i, page) in PAGES.iter().enumerate() {
            assert_eq!(find(page.id), Some(i), "duplicate id {}", page.id);
            assert!(!page.description.is_empty(), "{}", page.id);
            assert!(
                !matches!(page.id, "home" | "overview"),
                "{} is reserved for the shell",
                page.id
            );
        }
    }

    #[test]
    fn groups_map_to_sections() {
        assert_eq!(Section::of_group(FOUNDATIONS), Section::Foundations);
        assert_eq!(Section::of_group(FORMS), Section::Components);
        assert_eq!(Section::of_group("T3 · Shell"), Section::Patterns);
        assert_eq!(Section::of_group("Carbon · Patterns"), Section::Patterns);
    }
}
