/// The reference artifact's group order (`components/index.d.ts` sections).
/// Other groups (`T3 · …`, `Ghost · …`, `Carbon · Patterns`) follow in
/// first-use order.
pub const GROUP_ORDER: &[&str] = &[
    FOUNDATIONS,
    ACTIONS,
    FORMS,
    DATA_DISPLAY,
    FEEDBACK,
    NAVIGATION,
    OVERLAYS,
    LAYOUT,
    CHAT_AI,
];

/// The gallery's top-level sections (the header's navigation).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Section {
    /// Color, type, layout, motion and icons.
    Foundations,
    /// The shadcn component groups and Chat & AI.
    Components,
    /// `T3 · …`, `Ghost · …` and `Carbon · Patterns`.
    Patterns,
}

impl Section {
    /// Every section, in header order.
    pub const ALL: [Section; 3] = [Self::Foundations, Self::Components, Self::Patterns];

    /// The section's name.
    pub const fn title(self) -> &'static str {
        match self {
            Self::Foundations => "Foundations",
            Self::Components => "Components",
            Self::Patterns => "Patterns",
        }
    }

    /// One line about the section (home and overview).
    pub const fn summary(self) -> &'static str {
        match self {
            Self::Foundations => {
                "Color tokens in four themes, IBM Plex type, the 2x grid, motion and Material Symbols Sharp."
            }
            Self::Components => {
                "Every shadcn/ui component drawn in Carbon v11, plus Chat & AI. Live, keyboard-ready, themeable."
            }
            Self::Patterns => {
                "Carbon patterns and the T3 Code and Ghost pattern libraries, composed from the components."
            }
        }
    }

    /// The section's Material symbol.
    pub const fn icon(self) -> &'static str {
        match self {
            Self::Foundations => "palette",
            Self::Components => "widgets",
            Self::Patterns => "dashboard",
        }
    }

    /// The section of a navigation group.
    pub fn of_group(group: &str) -> Self {
        if group == FOUNDATIONS {
            Self::Foundations
        } else if group.starts_with("T3 · ")
            || group.starts_with("Ghost · ")
            || group.starts_with("Carbon · ")
        {
            Self::Patterns
        } else {
            Self::Components
        }
    }
}

/// A group's Material symbol (the side nav and thumbnails without a specimen).
pub fn group_icon(group: &str) -> &'static str {
    match group {
        FOUNDATIONS => "palette",
        ACTIONS => "touch_app",
        FORMS => "edit_note",
        DATA_DISPLAY => "table_chart",
        FEEDBACK => "notifications",
        NAVIGATION => "explore",
        OVERLAYS => "layers",
        LAYOUT => "view_quilt",
        CHAT_AI => "forum",
        _ => "dashboard",
    }
}

