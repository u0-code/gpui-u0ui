//! The page registry: every gallery page, its navigation group and how to
//! build it.
//!
//! # Adding a page
//!
//! Write `pages/<name>.rs` exposing `pub fn build(&mut Window, &mut App) -> AnyView`
//! (see [`crate::page`]), add `pub mod <name>;` to `pages/mod.rs`, then add one
//! line to [`PAGES`]:
//!
//! ```ignore
//! PageDef::new("tag-input", "TagInput", FORMS, Component::TagInput.summary(), pages::tag_input::build),
//! ```
//!
//! Optional builders on the same line: `.thumbnail(f)` (the overview card's
//! live specimen; the group's icon otherwise) and `.specs(f)` (a Specs tab).
//! Navigation, the overview, the ⌘K palette, `--page <id>` and `--capture`
//! pick the page up from here.
use crate::generated::descriptions::Component;
use crate::{pages, specs, thumbnails};
use gpui_kit::{AnyElement, AnyView, App, Window};

/// Builds a page's live view (called once, then cached).
pub type BuildFn = fn(&mut Window, &mut App) -> AnyView;
/// Draws a small live specimen or a Specs view.
pub type DrawFn = fn(&mut Window, &mut App) -> AnyElement;

/// One gallery page.
pub struct PageDef {
    /// Stable id for `--page <id>` (the reference component id, kebab-case).
    pub id: &'static str,
    /// Navigation and page title.
    pub title: &'static str,
    /// Navigation group (the reference artifact's groups).
    pub group: &'static str,
    /// The description under the title: the reference README's first sentence
    /// (`Component::Button.summary()`, generated by `u0ui-codegen`), or a text
    /// of its own for non-component pages.
    pub description: &'static str,
    /// Build the page's live view.
    pub build: BuildFn,
    /// The overview card's specimen.
    pub thumbnail: Option<DrawFn>,
    /// The Specs tab (anatomy, measurements, state colors).
    pub specs: Option<DrawFn>,
}

impl PageDef {
    /// A page with no thumbnail and no Specs tab.
    pub const fn new(
        id: &'static str,
        title: &'static str,
        group: &'static str,
        description: &'static str,
        build: BuildFn,
    ) -> Self {
        Self {
            id,
            title,
            group,
            description,
            build,
            thumbnail: None,
            specs: None,
        }
    }

    /// The overview card's live specimen.
    pub const fn thumbnail(mut self, thumbnail: DrawFn) -> Self {
        self.thumbnail = Some(thumbnail);
        self
    }

    /// A Specs tab beside the page's Overview.
    pub const fn specs(mut self, specs: DrawFn) -> Self {
        self.specs = Some(specs);
        self
    }

    /// The top-level section the page belongs to.
    pub fn section(&self) -> Section {
        Section::of_group(self.group)
    }
}

